export type TranslationKey = keyof typeof TRANSLATIONS.es;

export function translateRating(scale: RatingScale | null, lang: Language): string {
  if (!scale) return '—';
  const dict = TRANSLATIONS[lang];
  switch (scale) {
    case 'poor':
      return dict.ratingPoor;
    case 'normal':
      return dict.ratingNormal;
    case 'good':
      return dict.ratingGood;
    case 'excellent':
      return dict.ratingExcellent;
  }
}

export function tKey(lang: Language, key: TranslationKey): string {
  return TRANSLATIONS[lang][key];
}
